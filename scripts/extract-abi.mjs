#!/usr/bin/env node
// Extract the CCA ABI subset from upstream Solidity interfaces.
//
// Usage: node scripts/extract-abi.mjs <path-to-continuous-clearing-auction-checkout>
//
// Reads src/interfaces/*.sol, src/libraries/{CheckpointLib,BidLib,StepLib}.sol and
// src/lens/TickDataLens.sol, turns every external function, event and error into a
// human-readable signature, resolves user-defined types, validates with viem's parseAbi,
// and writes src/abi/cca.ts. No Solidity compiler is run.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { parseAbi } from 'viem';

const root = process.argv[2];
if (!root) {
  console.error('usage: extract-abi.mjs <upstream-checkout>');
  process.exit(2);
}

const commit = execFileSync('git', ['-C', root, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();

const files = {
  auction: [
    'src/interfaces/IContinuousClearingAuction.sol',
    'src/interfaces/IAuctionStorage.sol',
    'src/interfaces/IBidStorage.sol',
    'src/interfaces/ICheckpointStorage.sol',
    'src/interfaces/IStepStorage.sol',
    'src/interfaces/ITickStorage.sol',
  ],
  structs: [
    'src/libraries/CheckpointLib.sol',
    'src/libraries/BidLib.sol',
    'src/libraries/StepLib.sol',
    'src/interfaces/ITickStorage.sol',
    'src/lens/TickDataLens.sol',
  ],
  lens: ['src/lens/TickDataLens.sol'],
};

// User-defined value types and interface types that are addresses/uint256 on the wire.
const aliases = {
  ValueX7: 'uint256',
  IValidationHook: 'address',
  IContinuousClearingAuction: 'address',
};

const strip = (src) => src.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '');
const read = (f) => strip(readFileSync(join(root, f), 'utf8'));

function structs(src) {
  const out = {};
  for (const m of src.matchAll(/struct\s+(\w+)\s*\{([^}]*)\}/g)) {
    out[m[1]] = m[2]
      .split(';')
      .map((x) => x.trim())
      .filter(Boolean)
      .map((x) => x.replace(/\s+/g, ' '));
  }
  return out;
}

function normalise(sig) {
  let s = sig.replace(/\s+/g, ' ').trim();
  s = s.replace(/\boverride\s*(\([^)]*\))?/g, '');
  s = s.replace(/\b(calldata|memory|storage|virtual)\b/g, '');
  for (const [k, v] of Object.entries(aliases)) s = s.replace(new RegExp(`\\b${k}\\b`, 'g'), v);
  return s
    .replace(/\s+/g, ' ')
    .replace(/\s+([,)])/g, '$1')
    .replace(/\(\s+/g, '(')
    .trim();
}

function declarations(src, kinds) {
  const out = [];
  const re = new RegExp(`\\b(${kinds.join('|')})\\s+\\w+\\s*\\([\\s\\S]*?;`, 'g');
  for (const m of src.matchAll(re)) {
    let d = m[0].replace(/;$/, '');
    if (d.startsWith('function')) {
      // Keep visibility/mutability/returns, drop bodies (interfaces have none).
      if (!/\bexternal\b|\bpublic\b/.test(d)) continue;
      d = d.replace(/\{[\s\S]*$/, '');
    }
    out.push(normalise(d));
  }
  return out;
}

const allStructs = {};
for (const f of files.structs) Object.assign(allStructs, structs(read(f)));
const structSigs = Object.entries(allStructs).map(
  ([name, fields]) => `struct ${name} { ${fields.map((f) => normalise(f)).join('; ')}; }`,
);

const auctionDecls = new Set();
for (const f of files.auction) {
  for (const d of declarations(read(f), ['function', 'event', 'error'])) auctionDecls.add(d);
}
// Implementation-only public getters the tool reads (not declared in interfaces).
auctionDecls.add('function MAX_BID_PRICE() view returns (uint256)');

const lensDecls = new Set(declarations(read(files.lens[0]), ['function']));

const used = (decls) =>
  structSigs.filter((s) => {
    const name = s.split(' ')[1];
    return [...decls].some((d) => new RegExp(`\\b${name}\\b`).test(d));
  });

const auctionHuman = [...used(auctionDecls), ...auctionDecls];
const lensHuman = [...used(lensDecls), ...lensDecls].map((s) =>
  s.replace(/\bpublic view\b/, 'view'),
);

const auctionAbi = parseAbi(auctionHuman);
const lensAbi = parseAbi(lensHuman);

const header = `// Generated by scripts/extract-abi.mjs from Uniswap/continuous-clearing-auction.
// Do not edit by hand. Upstream commit: ${commit}
// Upstream license: MIT. See THIRD_PARTY_LICENSES.md.
`;
const body = `${header}
export const UPSTREAM_COMMIT = '${commit}' as const;

export const ccaAbi = ${JSON.stringify(auctionAbi, null, 2)} as const;

export const tickDataLensAbi = ${JSON.stringify(lensAbi, null, 2)} as const;
`;
writeFileSync(new URL('../src/abi/cca.ts', import.meta.url), body);
console.log(
  `wrote src/abi/cca.ts: ${auctionAbi.length} auction entries, ${lensAbi.length} lens entries @ ${commit}`,
);
